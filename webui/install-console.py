#!/usr/bin/env python3
"""Install the per-role user unit and shim for the Sparknet console.

The console runs as the operator, not root: it reads the role state and Qdrant
with the session/token already configured. The unit is a user unit; the shim
keeps the vault relocatable. This installer does not create the console token.

Usage::

    webui/install-console.py --role peer --apply
    webui/install-console.py --role master --check
"""

from __future__ import annotations

import argparse
import json
import shutil
import stat
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UNIT = ROOT / "webui" / "systemd" / "sparknet-console@.service"
BIN = Path.home() / ".local" / "bin" / "sparknet-console"
USER_UNIT = Path.home() / ".config" / "systemd" / "user" / "sparknet-console@.service"


class InstallError(RuntimeError):
    pass


def role_config(role: str) -> tuple[dict, Path]:
    role_root = ROOT / f"{role}-node"
    path = role_root / "configs" / "webui" / "console.json"
    try:
        config = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise InstallError(f"cannot read {path}: {exc}") from exc
    return config, role_root


def python_path() -> str:
    candidate = ROOT / ".venv" / "bin" / "python"
    if candidate.is_file():
        return str(candidate)
    return sys.executable


def shim_text() -> str:
    return (
        "#!/bin/sh\n"
        "# Generated by webui/install-console.py — re-run if the vault moves.\n"
        f'exec {python_path()!r} {str(ROOT / "scripts" / "sparknet-console.py")!r} "$@"\n'
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="install the Sparknet console user unit")
    parser.add_argument("--role", choices=("peer", "master"), required=True)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        config, role_root = role_config(args.role)
        token = Path(str(config.get("token_file") or ""))
        if not token.is_absolute():
            token = role_root / token
        if not token.is_file():
            raise InstallError(f"console token is missing: {token} (create it at 0600 first)")
        if stat.S_IMODE(token.stat().st_mode) != 0o600:
            raise InstallError(f"console token {token} must be mode 0600")
        if args.check:
            print(f"install-console: {UNIT.is_file()} unit, token present, role {args.role}")
            return 0
        if not args.apply:
            print("install-console: dry-run; re-run with --apply")
            print(f"  shim: {BIN}")
            print(f"  unit: {USER_UNIT}")
            return 0
        BIN.parent.mkdir(parents=True, exist_ok=True)
        BIN.write_text(shim_text(), encoding="utf-8")
        BIN.chmod(0o755)
        USER_UNIT.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(UNIT, USER_UNIT)
        subprocess.run(["systemctl", "--user", "daemon-reload"], check=True)
        subprocess.run(
            ["systemctl", "--user", "enable", "--now", f"sparknet-console@{args.role}.service"],
            check=True,
        )
        print(f"install-console: enabled sparknet-console@{args.role}.service")
        return 0
    except (InstallError, subprocess.CalledProcessError) as exc:
        print(f"install-console: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
